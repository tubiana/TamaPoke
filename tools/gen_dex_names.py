#!/usr/bin/env python3
"""Emit dex_names.h: every species' name in the UI languages that have their own.

    python tools/gen_dex_names.py           # fetch (cached) and write dex_names.h

DEX_TBL[].name is English and stays the CANONICAL name: the serial console, the
LAN wire and every test refer to species by it. This adds a per-language table
on top, read through one function, dexName(), so no screen can forget it.

Only names that DIFFER from English are stored. Portuguese has no row at all:
PokeAPI has no "pt" names because the Portuguese games use the English ones,
which is exactly what a null row falls back to. Spanish and Italian are mostly
English too, for the same reason.

Every name is folded to the firmware's charset (A-Z, 0-9, space, '.', '-'),
because the bitmap font has no accents: SALAMECHE, not Salameche with a grave.
The gender symbols become a letter in that language (NIDORAN F / W / H). The
script REFUSES to emit a character outside the charset rather than letting it
render as garbage on the panel.

Shares gen_dex_data.py's cache (tools/pokeapi_cache/), so a refetch is free.
"""
import os
import re
import sys
import unicodedata
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from gen_dex_data import get  # noqa: E402  (same cache, same curl)

# firmware Lang order (i18n.h): ES, EN, FR, DE, IT, PT. EN and PT are not here:
# their rows are null and fall back to DEX_TBL.
LANGS = [('es', 'ES'), ('fr', 'FR'), ('de', 'DE'), ('it', 'IT')]

# female / male, in each language's own word. Spanish keeps H (hembra) to match
# the NIDORAN H the canonical table has always used.
GENDER = {
    'es': ('H', 'M'), 'fr': ('F', 'M'), 'de': ('W', 'M'), 'it': ('F', 'M'),
}

ALLOWED = re.compile(r'^[A-Z0-9 .\-]+$')
MAX_LEN = 12   # Combatant::name is char[13]; the longest English name is 12 too


def read_dex():
    """The canonical English names, straight out of the committed dex.h, so the
    comparison is against what the firmware actually draws."""
    src = open(os.path.join(ROOT, 'dex.h'), encoding='utf-8').read()
    count = int(re.search(r'#define DEX_COUNT (\d+)', src).group(1))
    names = {}
    for m in re.finditer(r'\{ "([^"]*)",.*?// (\d+) ', src):
        names[int(m.group(2))] = m.group(1)
    missing = [n for n in range(1, count + 1) if n not in names]
    if missing:
        raise SystemExit('dex.h parse missed %d species, first %d' % (len(missing), missing[0]))
    return count, names


def fold(name, lang):
    fem, mal = GENDER[lang]
    s = name.replace('♀', ' ' + fem).replace('♂', ' ' + mal)
    s = s.replace('ß', 'ss')                     # German sharp s
    s = s.replace('œ', 'oe').replace('Œ', 'OE')
    s = unicodedata.normalize('NFKD', s)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    s = s.replace("'", '').replace('’', '')      # as FARFETCHD
    s = s.replace(':', ' ')                           # as TYPE NULL
    s = re.sub(r'\s+', ' ', s).strip().upper()
    if not ALLOWED.match(s):
        raise SystemExit('%s name %r folds to %r, outside the font charset' % (lang, name, s))
    return s


def alnum(s):
    return re.sub(r'[^A-Z0-9]', '', s)


def main():
    count, english = read_dex()
    url = 'https://pokeapi.co/api/v2/pokemon-species/%d'
    # warm the cache in parallel; get() makes its directory unguarded, so first
    os.makedirs(os.path.join(HERE, "pokeapi_cache"), exist_ok=True)
    with ThreadPoolExecutor(16) as ex:
        species = list(ex.map(lambda n: get(url % n), range(1, count + 1)))

    rows = {code: {} for _, code in LANGS}
    for n, sp in enumerate(species, start=1):
        by_lang = {e['language']['name']: e['name'] for e in sp['names']}
        for lang, code in LANGS:
            if lang not in by_lang:
                continue                  # falls back to English, like PT
            v = fold(by_lang[lang], lang)
            if len(v) > MAX_LEN:
                raise SystemExit('%s #%d %r is %d chars, the battle name holds %d'
                                 % (code, n, v, len(v), MAX_LEN))
            # PORYGON-Z vs PORYGON Z is the same name spelt by a different hand,
            # not a translation; the canonical spelling wins
            if alnum(v) != alnum(english[n]):
                rows[code][n] = v

    out = []
    out.append('#pragma once')
    out.append('// GENERATED by tools/gen_dex_names.py from PokeAPI -- do not edit.')
    out.append('// A species name per UI language, folded to the font charset. A null')
    out.append('// entry (or a null row: EN, PT) means "same as DEX_TBL[].name". Read it')
    out.append('// through dexName(), never directly.')
    out.append('#include "dex.h"')
    out.append('')
    for _, code in LANGS:
        out.append('static const char *const DEX_NAMES_%s[DEX_COUNT + 1] = {' % code)
        for n in range(0, count + 1):
            v = rows[code].get(n)
            out.append('  %s,  // %d' % ('"%s"' % v if v else 'nullptr', n))
        out.append('};')
        out.append('')
    out.append('// indexed by Lang: ES, EN, FR, DE, IT, PT')
    out.append('static const char *const *const DEX_NAMES[6] = {')
    out.append('  DEX_NAMES_ES, nullptr, DEX_NAMES_FR, DEX_NAMES_DE, DEX_NAMES_IT, nullptr,')
    out.append('};')
    open(os.path.join(ROOT, 'dex_names.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
    for _, code in LANGS:
        print('%s: %d of %d differ from English' % (code, len(rows[code]), count))


if __name__ == '__main__':
    main()
