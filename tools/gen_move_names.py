#!/usr/bin/env python3
"""Emit move_names.h: every move's name in the UI languages that have their own.

    python tools/gen_move_names.py

The move-name twin of gen_dex_names.py, and built the same way: MOVE_TBL[].name
stays the canonical English (the console, the LAN narration and the tests use
it), only names that DIFFER are stored, and the firmware reads them through one
function, moveName(). Same folding to the font charset, too.

**Move names are capped at 12 characters** (see dex_moves.py: four buttons
across the round panel at text size 2), and the English list was already
shortened to fit (ANCIENTPOWER, DAZZLE GLEAM). Some translations are longer, so
SHORT holds a hand-made form for each; the script FAILS on any name over 12
without one, rather than letting it run off a button. Where an older game had a
shorter official name it is used (FR: LANCE-FLAMME, TENEBRES).

Index i here is MOVE_TBL index i -- dex_moves.MOVES position + 1, slot 0 being
"-" -- the same append-only numbering gen_moves.py uses.
"""
import os
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from gen_dex_data import get           # noqa: E402  (shared cache)
from gen_dex_names import LANGS, fold, alnum  # noqa: E402
from dex_moves import MOVES           # noqa: E402

MAX_LEN = 12

# (lang, English name) -> a short form that fits. Only the ones PokeAPI gives
# longer than MAX_LEN; a new move that needs one fails the run until added.
SHORT = {
    ('fr', 'FLAMETHROWER'): 'LANCE-FLAMME',   # Gen 1-5 spelling
    ('fr', 'ANCIENTPOWER'): 'POUV.ANTIQUE',
    ('fr', 'NIGHT SHADE'): 'TENEBRES',        # Gen 1-4 name
    ('fr', 'DAZZLE GLEAM'): 'ECLAT MAGIQ.',
    ('fr', 'MOONBLAST'): 'POUV.LUNAIRE',
    ('es', 'QUICK ATTACK'): 'ATAQ. RAPIDO',
    ('es', 'HI JUMP KICK'): 'PATADA SALTO',
    ('es', 'POISON STING'): 'PICOTAZO VEN',
    ('es', 'IRON HEAD'): 'CAB. HIERRO',
    ('es', 'FLASH CANNON'): 'CANON RESPL.',
    ('es', 'DAZZLE GLEAM'): 'BRILLO MAG.',
    ('es', 'STRING SHOT'): 'DISP. DEMORA',
    ('it', 'QUICK ATTACK'): 'ATT. RAPIDO',
    ('it', 'MEGA DRAIN'): 'MEGASSORBIM.',
    ('it', 'SEISMIC TOSS'): 'MOV. SISMICO',
    ('it', 'SUBMISSION'): 'SOTTOMISS.',
    ('it', 'NIGHT SHADE'): 'OMBRA NOTT.',
}


def main():
    # slot 0 is MV_NONE ("-"); STRUGGLE has no slug in dex_moves (it keeps the
    # learnset fetcher off it) but PokeAPI knows it all the same
    moves = [(name, slug or 'struggle') for name, slug, *_ in MOVES]
    with ThreadPoolExecutor(16) as ex:
        data = list(ex.map(lambda m: get('https://pokeapi.co/api/v2/move/%s' % m[1]), moves))

    rows = {code: {} for _, code in LANGS}
    used = set()
    for i, ((en, _slug), d) in enumerate(zip(moves, data), start=1):
        by_lang = {e['language']['name']: e['name'] for e in d['names']}
        for lang, code in LANGS:
            if lang not in by_lang:
                continue
            v = fold(by_lang[lang], lang)
            if len(v) > MAX_LEN:
                if (lang, en) not in SHORT:
                    raise SystemExit('%s %s -> %r is %d chars; add a SHORT form'
                                     % (code, en, v, len(v)))
                v = SHORT[(lang, en)]
                used.add((lang, en))
                fold(v, lang)                       # the short form must fit the font too
                if len(v) > MAX_LEN:
                    raise SystemExit('SHORT %s %s is still %d chars' % (code, en, len(v)))
            if alnum(v) != alnum(en):
                rows[code][i] = v
    stale = set(SHORT) - used
    if stale:
        raise SystemExit('SHORT entries no longer needed: %s' % sorted(stale))

    count = len(MOVES) + 1
    out = ['#pragma once',
           '// GENERATED by tools/gen_move_names.py from PokeAPI -- do not edit.',
           '// A move name per UI language, folded to the font charset and capped',
           '// at 12. A null entry (or a null row: EN, PT) means "same as',
           '// MOVE_TBL[].name". Read it through moveName(), never directly.',
           '#include "moves.h"', '']
    for _, code in LANGS:
        out.append('static const char *const MOVE_NAMES_%s[MOVE_COUNT] = {' % code)
        for i in range(count):
            v = rows[code].get(i)
            out.append('  %s,  // %d' % ('"%s"' % v if v else 'nullptr', i))
        out.append('};')
        out.append('')
    out.append('// indexed by Lang: ES, EN, FR, DE, IT, PT')
    out.append('static const char *const *const MOVE_NAMES[6] = {')
    out.append('  MOVE_NAMES_ES, nullptr, MOVE_NAMES_FR, MOVE_NAMES_DE, MOVE_NAMES_IT, nullptr,')
    out.append('};')
    open(os.path.join(ROOT, 'move_names.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
    for _, code in LANGS:
        print('%s: %d of %d moves differ from English' % (code, len(rows[code]), count - 1))


if __name__ == '__main__':
    main()
